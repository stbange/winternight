/* ---------------- Sky ---------------- */

static const char *k_fullscreen_vs =
    "out vec2 v_uv;\n"
    "void main() {\n"
    "  vec2 p = vec2(float((gl_VertexID << 1) & 2), float(gl_VertexID & 2));\n"
    "  v_uv = p;\n"
    "  gl_Position = vec4(p * 2.0 - 1.0, 0.0, 1.0);\n"
    "}\n";

static const char *k_sky_fs =
    "in vec2 v_uv;\n"
    "uniform mat4 u_inv_viewproj;\n"
    "uniform vec3 u_sky_top;\n"
    "uniform vec3 u_sky_horizon;\n"
    "uniform vec3 u_moon_dir;\n"
    "uniform vec3 u_moon_col;\n"
    "uniform vec3 u_fog_col;\n"
    "uniform float u_time;\n"
    "uniform float u_aurora;\n"
    "layout(location=0) out vec4 o_color;\n"
    "uint hash3(ivec3 p, uint seed) {\n"
    "  uint h = seed ^ 0x9E3779B9u;\n"
    "  h ^= uint(p.x) * 0x85EBCA6Bu; h = (h << 13u) | (h >> 19u);\n"
    "  h ^= uint(p.y) * 0xC2B2AE35u; h = (h << 17u) | (h >> 15u);\n"
    "  h ^= uint(p.z) * 0x27D4EB2Fu;\n"
    "  h ^= h >> 16u; h *= 0x7FEB352Du; h ^= h >> 15u; h *= 0x846CA68Bu; h ^= h >> 16u;\n"
    "  return h;\n"
    "}\n"
    "void main() {\n"
    "  vec4 p = u_inv_viewproj * vec4(v_uv * 2.0 - 1.0, 1.0, 1.0);\n"
    "  vec3 dir = normalize(p.xyz / p.w);\n"
    "  float up = clamp(dir.y, 0.0, 1.0);\n"
    "  vec3 col = mix(u_sky_horizon, u_sky_top, pow(up, 0.45));\n"
    "  col = mix(u_fog_col, col, smoothstep(-0.05, 0.12, dir.y));\n"
    "  if (dir.y > -0.02) {\n"
    "    ivec3 c = ivec3(floor(dir * 260.0));\n"
    "    uint h = hash3(c, 17u);\n"
    "    float band = 1.0 - smoothstep(0.0, 0.35, abs(dot(dir, normalize(vec3(0.4, 0.3, -0.85)))));\n"
    "    uint thresh = uint(18.0 + band * 60.0);\n"
    "    if ((h & 1023u) < thresh) {\n"
    "      float b = float((h >> 10u) & 255u) / 255.0;\n"
    "      float tw = 0.75 + 0.25 * sin(u_time * (1.0 + b * 3.0) + float(h & 63u));\n"
    "      col += vec3(0.75, 0.8, 1.0) * (0.25 + 0.75 * b * b) * tw * smoothstep(-0.02, 0.15, dir.y);\n"
    "    }\n"
    "    col += vec3(0.05, 0.06, 0.12) * band * smoothstep(0.0, 0.3, dir.y);\n"
    "  }\n"
    "  float md = dot(dir, u_moon_dir);\n"
    "  if (md > 0.9993) {\n"
    "    ivec3 mc = ivec3(floor(dir * 900.0));\n"
    "    float crater = float(hash3(mc, 5u) & 7u) / 40.0;\n"
    "    col = u_moon_col * 1.25 + vec3(0.25) - crater;\n"
    "  } else {\n"
    "    col += u_moon_col * 0.35 * smoothstep(0.985, 0.9993, md);\n"
    "  }\n"
    "  if (u_aurora > 0.5 && dir.y > 0.05) {\n"
    "    float a = sin(dir.x * 9.0 + u_time * 0.2) * 0.5 + 0.5;\n"
    "    col += vec3(0.1, 0.9, 0.6) * a * smoothstep(0.05, 0.3, dir.y) * (1.0 - smoothstep(0.3, 0.7, dir.y)) * 0.25;\n"
    "  }\n"
    "  o_color = vec4(col, 0.0);\n"
    "}\n";

