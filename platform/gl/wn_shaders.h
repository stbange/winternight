/* ---------------- Post-processing ---------------- */

/* Glow: keep emissive pixels (alpha) and blur them. */
static const char *k_glow_down_fs =
    "in vec2 v_uv;\n"
    "uniform sampler2D u_src;\n"
    "uniform vec2 u_texel;\n"
    "layout(location=0) out vec4 o_color;\n"
    "void main() {\n"
    "  vec3 acc = vec3(0.0);\n"
    "  for (int y = -1; y <= 2; y++) for (int x = -1; x <= 2; x++) {\n"
    "    vec4 c = texture(u_src, v_uv + vec2(float(x), float(y)) * u_texel);\n"
    "    acc += c.rgb * c.a;\n"
    "  }\n"
    "  o_color = vec4(acc / 16.0, 1.0);\n"
    "}\n";

static const char *k_blur_fs =
    "in vec2 v_uv;\n"
    "uniform sampler2D u_src;\n"
    "uniform vec2 u_dir;\n"
    "layout(location=0) out vec4 o_color;\n"
    "void main() {\n"
    "  vec3 c = texture(u_src, v_uv).rgb * 0.227;\n"
    "  c += (texture(u_src, v_uv + u_dir).rgb + texture(u_src, v_uv - u_dir).rgb) * 0.195;\n"
    "  c += (texture(u_src, v_uv + u_dir * 2.0).rgb + texture(u_src, v_uv - u_dir * 2.0).rgb) * 0.122;\n"
    "  c += (texture(u_src, v_uv + u_dir * 3.0).rgb + texture(u_src, v_uv - u_dir * 3.0).rgb) * 0.054;\n"
    "  c += (texture(u_src, v_uv + u_dir * 4.0).rgb + texture(u_src, v_uv - u_dir * 4.0).rgb) * 0.016;\n"
    "  o_color = vec4(c, 1.0);\n"
    "}\n";

/* Final combine at internal resolution: scene + glow + overlay, then the
 * 64-colour palette with 4x4 ordered dithering (spec retro-rendering). */
static const char *k_post_fs =
    "in vec2 v_uv;\n"
    "uniform sampler2D u_scene;\n"
    "uniform sampler2D u_glow;\n"
    "uniform sampler2D u_overlay;\n"
    "uniform highp sampler3D u_lut;\n"
    "uniform float u_glow_on;\n"
    "uniform float u_palette_on;\n"
    "uniform float u_vignette;\n"
    "layout(location=0) out vec4 o_color;\n"
    "const float k_bayer[16] = float[16](0.0, 8.0, 2.0, 10.0, 12.0, 4.0, 14.0, 6.0, 3.0, 11.0, 1.0, 9.0, 15.0, 7.0, 13.0, 5.0);\n"
    "void main() {\n"
    "  vec3 c = texture(u_scene, v_uv).rgb;\n"
    "  if (u_glow_on > 0.5) c += texture(u_glow, v_uv).rgb * 1.6;\n"
    "  if (u_vignette > 0.0) {\n"
    "    float r = length(v_uv - 0.5) * 1.6;\n"
    "    c *= 1.0 - u_vignette * smoothstep(0.45, 1.0, r);\n"
    "  }\n"
    "  vec4 ov = texture(u_overlay, vec2(v_uv.x, 1.0 - v_uv.y));\n"
    "  c = mix(c, ov.rgb, ov.a);\n"
    "  if (u_palette_on > 0.5) {\n"
    "    ivec2 px = ivec2(gl_FragCoord.xy) & 3;\n"
    "    float b = (k_bayer[px.y * 4 + px.x] + 0.5) / 16.0 - 0.5;\n"
    "    c = clamp(c + b / 14.0, 0.0, 1.0);\n"
    "    c = texture(u_lut, c * (31.0 / 32.0) + 0.5 / 32.0).rgb;\n"
    "  }\n"
    "  o_color = vec4(c, 1.0);\n"
    "}\n";

