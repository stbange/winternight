static const uint8_t *find_glyph(char c)
{
    if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
    for (size_t i = 0; i < sizeof k_glyphs / sizeof k_glyphs[0]; i++)
        if (k_glyphs[i].c == c) return k_glyphs[i].rows;
    return NULL;
}

int wn_font_width(const char *text)
{
    int n = (int)strlen(text);
    return n ? n * WN_FONT_ADVANCE - 1 : 0;
}

void wn_font_draw(uint8_t *buf, int w, int h, int x, int y, const char *text)
{
    static const uint8_t box[WN_FONT_H] = {0x1f, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1f};
    for (const char *s = text; *s; s++, x += WN_FONT_ADVANCE) {
        const uint8_t *g = find_glyph(*s);
        if (!g) g = box;
        for (int r = 0; r < WN_FONT_H; r++)
            for (int c = 0; c < WN_FONT_W; c++) {
                if (!((g[r] >> (WN_FONT_W - 1 - c)) & 1)) continue;
                int px = x + c, py = y + r;
                if (px < 0 || py < 0 || px >= w || py >= h) continue;
                buf[py * w + px] = 255;
            }
    }
}
